    var currentLang: String = "zh"

    /** 根据 [currentLang] 获取 [key] 对应的翻译。找不到则返回 key 本身。 */
    fun tr(key: String, vararg args: Any?): String {
        val map = if (currentLang == "en") en else zh
        var result = map[key] ?: key
        if (args.isNotEmpty()) {
            result = result.format(*args)
        }
        return result
    }

