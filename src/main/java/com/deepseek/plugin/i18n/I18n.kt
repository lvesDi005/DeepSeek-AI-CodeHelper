package com.deepseek.plugin.i18n

/**
 * 国际化工具 — 集中管理所有用户可见字符串。
 *
 * 用法：在 UI 代码中调用 `I18n.tr("key")` 获取当前语言的字符串。
 * 语言切换后，提示用户关闭并重新打开面板以刷新界面。
 */
